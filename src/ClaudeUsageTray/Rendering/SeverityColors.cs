using System.Drawing;

namespace ClaudeUsageTray.Rendering;

// =============================================================================
//  深刻度の色
// -----------------------------------------------------------------------------
//  【設計思想】
//
//  1. しきい値を自前で持たない。
//     何 % から警告かはサーバーの severity が決める。自前で 80 / 90 を決めると
//     公式 UI と食い違い、どちらが正しいのか分からなくなる。
//
//  2. 色だけに意味を載せない。
//     ここは色を返すだけだが、UI 側では数値そのものも併記している。
//     色が見分けられなくても情報が失われないこと。
//
//  3. 緑を使わない。青 → 琥珀 → 赤 にする。
//     赤と緑は第 1・第 2 色覚で区別しづらい。青・琥珀・赤なら色相だけでなく
//     明度でも差が残るため、色覚に依存せず段階が伝わる。
// =============================================================================
internal static class SeverityColors
{
    /// <summary>
    /// severity ごとの数値の色。パネルの背景は常に暗いので暗色版だけでよい。
    /// </summary>
    public static Color For(int severityRank) => severityRank switch
    {
        0 => Color.FromArgb(0x6F, 0xB4, 0xEC),   // normal   : 青
        1 => Color.FromArgb(0xF0, 0xA8, 0x30),   // warning  : 琥珀
        _ => Color.FromArgb(0xF0, 0x6A, 0x6E),   // critical : 赤
    };
}
